        'FACT_FACTURACION_FLETE',
        'FACT_GASTOS_LIQUIDACION'
    );
BEGIN
    FOR i IN 1..v_tabs.COUNT LOOP
        -- Permiso con GRANT OPTION a BI_SEMANTIC para evitar ORA-01720 en vistas
        EXECUTE IMMEDIATE 'GRANT SELECT ON DWH_MART.' || v_tabs(i) || ' TO BI_SEMANTIC WITH GRANT OPTION';
        -- Permiso directo de lectura a BI_READER
        EXECUTE IMMEDIATE 'GRANT SELECT ON DWH_MART.' || v_tabs(i) || ' TO BI_READER';
        -- Permiso completo de gestión a ETL_RUNNER
        EXECUTE IMMEDIATE 'GRANT SELECT, INSERT, UPDATE, DELETE ON DWH_MART.' || v_tabs(i) || ' TO ETL_RUNNER';
    END LOOP;
END;
